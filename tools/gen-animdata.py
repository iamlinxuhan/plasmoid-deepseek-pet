#!/usr/bin/env python3
"""Generate package/contents/ui/AnimData.js from the converted WebP assets."""

import json
import os
import subprocess
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANIM_DIR = os.path.join(ROOT, "package", "contents", "ui", "assets", "anim")
SRC_DIRS = [
    os.path.join(ROOT, "reference", "dsh-pet-indesktop", "assets", "characters", "shenshen", "videos"),
    os.path.join(ROOT, "reference", "dsh-pet-src", "dsh-pet", "assets", "webm"),
]
SOURCE_ALIASES = {"原地漂浮踏步": "漂浮踏步", "原地左转奔跑": "左转奔跑"}
OUT = os.path.join(ROOT, "package", "contents", "ui", "AnimData.js")

data = {}
for filename in sorted(os.listdir(ANIM_DIR)):
    if not filename.endswith(".webp"):
        continue
    name = filename[:-5]
    path = os.path.join(ANIM_DIR, filename)
    image = Image.open(path)
    frames = getattr(image, "n_frames", 1)
    if frames < 2:
        sys.exit(f"not animated: {filename}")

    duration = 0.0
    source_name = SOURCE_ALIASES.get(name, name)
    source = None
    for directory in SRC_DIRS:
        for root, _dirs, files in os.walk(directory):
            candidate = os.path.join(root, source_name + ".webm")
            if os.path.exists(candidate):
                source = candidate
                break
        if source:
            break
    if source:
        out = subprocess.check_output(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", source],
            text=True,
        ).strip()
        try:
            duration = round(float(out), 3)
        except ValueError:
            duration = 0.0
    data[name] = {"frames": frames, "duration": duration}

lines = [
    ".pragma library",
    "// Generated by tools/gen-animdata.py — do not edit by hand.",
    "var DATA = {",
]
for name in sorted(data):
    item = data[name]
    lines.append(
        "    %s: { frames: %d, duration: %s },"
        % (json.dumps(name, ensure_ascii=False), item["frames"], item["duration"])
    )
lines += [
    "};",
    "",
    "function frameCount(name) {",
    "    var d = DATA[name];",
    "    return d ? d.frames : 0;",
    "}",
    "",
    "function duration(name) {",
    "    var d = DATA[name];",
    "    return d ? d.duration : 0;",
    "}",
    "",
]
with open(OUT, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines))

print("wrote %s (%d animations)" % (OUT, len(data)))
