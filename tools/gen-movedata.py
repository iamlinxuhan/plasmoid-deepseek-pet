#!/usr/bin/env python3
"""Generate package/contents/ui/MoveData.js from dsh-pet-indesktop move_strides.json."""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(
    ROOT, "reference", "dsh-pet-indesktop", "assets", "characters", "shenshen", "videos", "move_strides.json"
)
OUT = os.path.join(ROOT, "package", "contents", "ui", "MoveData.js")

# 本项目沿用旧素材文件名；升级源里有两个动作改了名。
ALIASES = {
    "左转奔跑": "原地左转奔跑",
    "漂浮踏步": "原地漂浮踏步",
}

with open(SRC, encoding="utf-8") as handle:
    raw = json.load(handle)

data = {}
for name, item in raw.items():
    if name.startswith("_"):
        continue
    target = ALIASES.get(name, name)
    curve = [round(float(v), 4) for v in item["curve"]]
    data[target] = {"stride": round(float(item["stride"]), 2), "curve": curve}

lines = [
    ".pragma library",
    "// Generated by tools/gen-movedata.py from dsh-pet-indesktop's move_strides.json.",
    "// curve[i] = 源帧 i 在一圈步态内的累计位移进度（0..1），静帧段走平。",
    "var MOVES = {",
]
for name in sorted(data):
    item = data[name]
    curve = ", ".join("%g" % v for v in item["curve"])
    lines.append('    %s: { stride: %g, curve: [%s] },' % (json.dumps(name, ensure_ascii=False), item["stride"], curve))
lines += [
    "};",
    "",
    "function stride(name) {",
    "    var d = MOVES[name];",
    "    return d ? d.stride : 120;",
    "}",
    "",
    "function curveProgress(name, frame, frameCount) {",
    "    var d = MOVES[name];",
    "    if (frameCount <= 1) {",
    "        return 1.0;",
    "    }",
    "    if (!d || !d.curve || d.curve.length === 0) {",
    "        return Math.max(0, Math.min(frameCount - 1, frame)) / (frameCount - 1);",
    "    }",
    "    var pos = Math.max(0, Math.min(frameCount - 1, frame)) / (frameCount - 1) * (d.curve.length - 1);",
    "    var lo = Math.floor(pos);",
    "    var hi = Math.min(lo + 1, d.curve.length - 1);",
    "    var frac = pos - lo;",
    "    return d.curve[lo] + (d.curve[hi] - d.curve[lo]) * frac;",
    "}",
    "",
]
with open(OUT, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines))

print("wrote %s (%d moves)" % (OUT, len(data)))
